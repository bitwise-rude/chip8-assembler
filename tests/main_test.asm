; ==========================================
; CHIP-8 INSTRUCTION TEST
; ==========================================

; Initialize
ld v0, 0
ld v1, 0
ld v2, 1
ld v3, 5
ld v4, $FF
ld v5, %10101010

cls

; ==========================================
; TEST 1: Arithmetic
; ==========================================

add v0, 10
add v0, v2
sub v0, v2

; V0 should now be 10
se v0, 10
jp fail

; ==========================================
; TEST 2: Logic
; ==========================================

ld v0, %11110000
ld v1, %10101010

and v0, v1
; V0 = 10100000

ld v0, %11110000
or v0, v1
; V0 = 11111010

ld v0, %11110000
xor v0, v1
; V0 = 01011010

; ==========================================
; TEST 3: Subroutine
; ==========================================

call test_sub
se v2, 5
jp fail

; ==========================================
; TEST 4: Sprite drawing
; ==========================================

ld v0, 30
ld v1, 14
ld v2, 1
ld f, v2

cls
drw v0, v1, 5

; ==========================================
; TEST 5: Key input
; ==========================================

wait_key:
ld v6, k

; ==========================================
; TEST 6: Random
; ==========================================

rnd v7, $FF

; ==========================================
; TEST 7: Timer
; ==========================================

ld v3, 60
ld dt, v3

timer_wait:
ld v4, dt
se v4, 0
jp timer_wait

; ==========================================
; SUCCESS
; ==========================================

cls

ld v0, 10
ld v1, 10
ld v2, 5
ld f, v2
drw v0, v1, 5

success:
jp success

; ==========================================
; SUBROUTINE
; ==========================================

test_sub:
ld v2, 4
add v2, 1
ret

; ==========================================
; FAILURE
; ==========================================

fail:
cls
ld v0, 0
ld v1, 0
ld v2, 15
ld f, v2
drw v0, v1, 5

failure:
jp failure
